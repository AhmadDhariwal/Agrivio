#!/usr/bin/env node
/**
 * Generates apps/frontend/src/environments/environment.generated.ts from
 * the AGRIVIO_PUBLIC_API_BASE_URL environment variable.
 *
 * Run this script before the Angular build in staging/production environments:
 *   node scripts/generate-frontend-env.mjs
 *
 * Local development: the committed default (http://localhost:3000) is used
 * without running this script. The script only needs to run when deploying.
 *
 * Cloudflare Pages build command:
 *   node scripts/generate-frontend-env.mjs && npm run build:frontend
 */
import { writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';
//worked solution but need to figure out how to make it run from the root directory
const __dirname = dirname(fileURLToPath(import.meta.url));

// const apiBaseUrl =
//   process.env['AGRIVIO_PUBLIC_API_BASE_URL'] || 'http://localhost:3000';
const configuredApiBaseUrl =
  process.env['AGRIVIO_PUBLIC_API_BASE_URL']?.trim();

const isCloudflarePages = process.env['CF_PAGES'] === '1';

if (!configuredApiBaseUrl && isCloudflarePages) {
  console.error(
    '[generate-frontend-env] AGRIVIO_PUBLIC_API_BASE_URL is required for Cloudflare Pages builds.',
  );
  process.exit(1);
}

const apiBaseUrl =
  configuredApiBaseUrl || 'http://localhost:3000';

// Validate: must be an absolute http(s) URL (mirrors validateWebPublicConfig).
try {
  const parsed = new URL(apiBaseUrl);
  if (parsed.protocol !== 'http:' && parsed.protocol !== 'https:') {
    throw new Error('protocol must be http or https');
  }
} catch {
  console.error(
    `[generate-frontend-env] AGRIVIO_PUBLIC_API_BASE_URL is not a valid http(s) URL: ${apiBaseUrl}`,
  );
  process.exit(1);
}

const outputPath = resolve(
  __dirname,
  '../apps/frontend/src/environments/environment.generated.ts',
);

const content =
  `// AUTO-GENERATED by scripts/generate-frontend-env.mjs — do not edit manually.\n` +
  `// Committed default: http://localhost:3000 (local development).\n` +
  `// Override by setting AGRIVIO_PUBLIC_API_BASE_URL before running the build script.\n` +
  `export const buildTimeApiBaseUrl = ${JSON.stringify(apiBaseUrl)};\n`;

writeFileSync(outputPath, content, 'utf8');
console.log(`[generate-frontend-env] publicApiBaseUrl = ${apiBaseUrl}`);
